#!/usr/bin/env python3
"""Calendar-edit end-to-end test in QA demo mode (?qa=1) at 390x844, touch. Usage: test_qa.py BASE_URL OUT_DIR"""
import asyncio, sys, os, json
from playwright.async_api import async_playwright
BASE, OUT = sys.argv[1], sys.argv[2]; os.makedirs(OUT, exist_ok=True)
FAIL=[]
def ok(c,msg):
    print(("PASS " if c else "FAIL ")+msg)
    if not c: FAIL.append(msg)
async def main():
  async with async_playwright() as p:
    b = await p.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--disable-dev-shm-usage"])
    ctx = await b.new_context(viewport={"width":390,"height":844}, device_scale_factor=2, is_mobile=True, has_touch=True,
        user_agent="Mozilla/5.0 (iPhone; CPU iPhone OS 17_5 like Mac OS X) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/17.5 Mobile/15E148 Safari/604.1")
    pg = await ctx.new_page(); errs=[]
    pg.on("pageerror", lambda e: errs.append("pageerror: "+str(e)))
    pg.on("console", lambda m: errs.append(f"console.{m.type}: {m.text}") if m.type=="error" else None)
    cdp = await ctx.new_cdp_session(pg)
    async def touch(t,x,y): await cdp.send("Input.dispatchTouchEvent",{"type":t,"touchPoints":[] if t=="touchEnd" else [{"x":x,"y":y}]})
    async def shot(n): await pg.wait_for_timeout(250); await pg.screenshot(path=f"{OUT}/{n}.png"); print("  shot", n)
    edits = lambda: pg.evaluate("JSON.parse(sessionStorage.getItem('dbw:qa:edits')||'{\"edits\":[]}').edits")
    await pg.goto(BASE+"?qa=1", wait_until="networkidle"); await pg.wait_for_timeout(700)
    await pg.evaluate("document.documentElement.style.setProperty('--sat','54px');document.documentElement.style.setProperty('--sab','34px')")
    dock = await pg.evaluate("[...document.querySelectorAll('.dock button')].map(b=>b.getAttribute('aria-label'))")
    ok("Today" not in dock, f"dock has no Today tab: {dock}")
    await shot("01-home-dock")
    # every link that opens the schedule goes to the Week view
    views = await pg.evaluate("[...document.querySelectorAll('[data-open=schedule],[data-app=week]')].map(b=>b.dataset.view)")
    ok(all(v=="week" for v in views), f"all schedule links open week: {views}")
    await pg.click('.dock [data-app="week"]'); await pg.wait_for_timeout(700)
    title = await pg.evaluate("document.querySelector('.ovh b').textContent")
    ok(title=="Week", "dock Week opens the Week view"); ok(await pg.evaluate("!document.querySelector('.ovb .seg')"), "no Today/Week toggle left")
    await pg.evaluate("document.querySelector('.wg').scrollIntoView({block:'start'});document.querySelector('.ovb').scrollTop-=70")
    await shot("02-week-view")
    blk = lambda sel: pg.evaluate("""s=>{const a=[...document.querySelectorAll('.wg [data-wkb]')].filter(i=>i.style.background.includes(s));const i=a[0];if(!i)return null;i.scrollIntoView({block:'center'});const r=i.getBoundingClientRect();return {id:i.dataset.wkb,x:r.left+r.width/2,y:r.top+Math.min(r.height/2,30),t:i.innerText}}""", sel)
    # ---- 1. tap to edit ----
    w = await blk("--work"); print("  work block", w)
    await pg.tap(f'.wg [data-wkb="{w["id"]}"]'); await pg.wait_for_timeout(400)
    ok(await pg.is_visible('.usheet #es_ok'), "tap opens the edit sheet")
    await shot("03-tap-edit-sheet")
    await pg.select_option('#es_s [data-p=h]','09'); await pg.select_option('#es_e [data-p=h]','17'); await pg.select_option('#es_e [data-p=m]','30')
    hint = await pg.inner_text('#es_h'); ok("8.5 h" in hint, f"duration hint: {hint}")
    await pg.tap('#es_ok'); await pg.wait_for_timeout(500)
    E = await edits(); ok(len(E)==1 and E[0]["op"]=="move" and E[0]["start"]=="09:00" and E[0].get("dur")==510, f"move edit saved: {E}")
    ok(await pg.evaluate("[...document.querySelectorAll('.wg [data-wkb].ed')].some(i=>i.innerText.includes('09:00'))"), "edited block shows 09:00 and the edited mark")
    ok(await pg.is_visible('.toast'), "toast with Undo shown")
    await shot("04-after-tap-edit")
    # ---- 2. long-press drag (touch) ----
    g = await blk("--workout"); print("  gym block", g)
    st0 = await pg.evaluate("document.querySelector('.ovb').scrollTop")
    colw = await pg.evaluate("document.querySelector('.wg .col').getBoundingClientRect().width+3")
    await touch("touchStart", g["x"], g["y"]); await pg.wait_for_timeout(600)
    for i in range(1,11): await touch("touchMove", g["x"]+colw*i/10, g["y"]+44*i/10); await pg.wait_for_timeout(30)
    ghost = await pg.evaluate("document.querySelector('.wg .ghost span')?.textContent"); ok(bool(ghost), f"drag ghost shows the new time: {ghost}")
    await shot("05-drag-in-progress")
    st1 = await pg.evaluate("document.querySelector('.ovb').scrollTop")
    await touch("touchEnd", 0, 0); await pg.wait_for_timeout(600)
    ok(abs(st1-st0)<2, f"page didn't scroll while dragging ({st0}->{st1})")
    E = await edits(); mv=[x for x in E if x.get("src",{}).get("type")=="workout"]
    ok(len(mv)==1 and mv[0]["start"]=="19:30" and mv[0]["date"]>mv[0]["src"]["date"], f"drag saved +1 day, +2 h, snapped: {mv}")
    ok(not await pg.is_visible('.usheet'), "drop doesn't open the editor")
    await shot("06-after-drag")
    # quick swipe on a block = scroll, not drag
    g2 = await blk("--sleep"); st0 = await pg.evaluate("document.querySelector('.ovb').scrollTop"); n0=len(await edits())
    await touch("touchStart", g2["x"], g2["y"])
    for i in range(1,9): await touch("touchMove", g2["x"], g2["y"]-20*i); await pg.wait_for_timeout(16)
    await touch("touchEnd",0,0); await pg.wait_for_timeout(700)
    st1 = await pg.evaluate("document.querySelector('.ovb').scrollTop")
    ok(len(await edits())==n0 and not await pg.is_visible('.usheet'), "quick swipe on a block makes no edit")
    ok(st1!=st0, f"quick swipe scrolls the page ({st0}->{st1})")
    # ---- 3. delete + undo ----
    m = await blk("--event"); print("  event block", m)
    await pg.tap(f'.wg [data-wkb="{m["id"]}"]'); await pg.wait_for_timeout(300); await pg.tap('#es_del'); await pg.wait_for_timeout(400)
    E = await edits(); ok(any(x["op"]=="delete" for x in E), "delete saved as a hide edit")
    await shot("07-after-delete-undo-toast")
    await pg.tap('.toast button'); await pg.wait_for_timeout(400)
    ok(not any(x["op"]=="delete" for x in await edits()), "Undo brings it back")
    m = await blk("--event"); await pg.tap(f'.wg [data-wkb="{m["id"]}"]'); await pg.wait_for_timeout(300); await pg.tap('#es_del'); await pg.wait_for_timeout(400)
    # ---- 4. add with ＋ ----
    await pg.tap('.fab'); await pg.wait_for_timeout(300)
    ok(await pg.is_visible('#es_l'), "＋ opens the add sheet with a title")
    d2 = await pg.evaluate("(()=>{const d=new Date(Date.now()+2*864e5);return new Intl.DateTimeFormat('en-CA',{timeZone:'America/Toronto'}).format(d)})()")
    await pg.fill('#es_l','Dentist'); await pg.fill('#es_d', d2)
    await pg.select_option('#es_s [data-p=h]','14'); await pg.select_option('#es_s [data-p=m]','00'); await pg.select_option('#es_e [data-p=h]','15'); await pg.select_option('#es_e [data-p=m]','30')
    await shot("08-add-sheet")
    await pg.tap('#es_ok'); await pg.wait_for_timeout(500)
    E = await edits(); ad=[x for x in E if x["op"]=="add"]; ok(len(ad)==1 and ad[0]["label"]=="Dentist" and ad[0]["date"]==d2 and ad[0]["dur"]==90, f"add saved: {ad}")
    has = await pg.evaluate("[...document.querySelectorAll('.dayrow button.ev')].some(b=>b.innerText.includes('Dentist')&&b.innerText.includes('14:00–15:30'))")
    ok(has, "added event shows in Day by day 14:00–15:30")
    # edit the added event's title from Day by day
    await pg.evaluate("[...document.querySelectorAll('.dayrow button.ev')].find(b=>b.innerText.includes('Dentist')).scrollIntoView({block:'center'})")
    await pg.evaluate("[...document.querySelectorAll('.dayrow button.ev')].find(b=>b.innerText.includes('Dentist')).click()"); await pg.wait_for_timeout(300)
    ok(await pg.input_value('#es_l')=="Dentist", "tapping your own event lets you edit its title")
    await pg.fill('#es_l','Dentist check-up'); await pg.tap('#es_ok'); await pg.wait_for_timeout(400)
    ok([x for x in await edits() if x["op"]=="add"][0]["label"]=="Dentist check-up", "title edit saved")
    await pg.evaluate("document.querySelector('.wg').scrollIntoView({block:'start'});document.querySelector('.ovb').scrollTop-=70"); await shot("09-week-with-edits")
    # ---- 5. overnight block: move the whole night shift ----
    ns = await pg.evaluate("""(()=>{const i=[...document.querySelectorAll('.wg [data-wkb]')].find(i=>i.style.background.includes('--ea'));i.scrollIntoView({block:'center'});return i.dataset.wkb})()""")
    await pg.tap(f'.wg [data-wkb="{ns}"]'); await pg.wait_for_timeout(300)
    await pg.select_option('#es_s [data-p=h]','21'); await pg.select_option('#es_e [data-p=h]','05'); await pg.select_option('#es_e [data-p=m]','00')
    ok("ends the next day" in await pg.inner_text('#es_h'), "overnight hint (+1)")
    await pg.tap('#es_ok'); await pg.wait_for_timeout(400)
    E = await edits(); ov=[x for x in E if x.get("src",{}).get("type")=="ea"]
    ok(len(ov)==1 and ov[0]["dur"]==480 and len(ov[0]["covers"])==1, f"overnight move covers the after-midnight piece: {ov}")
    evs = await pg.evaluate("__DBW.STORE.schedule.events.filter(e=>e.type==='ea').map(e=>e.date+' '+e.start+'-'+e.end+' '+e.label)")
    print("  ea events now:", evs[:4]); nd=ov[0]["covers"][0].split("@")[1]; ok(not any(e.startswith(nd+" 00:00-03:00") for e in evs) and any(e.startswith(nd+" 00:00-05:00") for e in evs), f"old after-midnight piece on {nd} hidden, moved piece shown")
    # ---- 6. Your changes card + reset to calendar ----
    await pg.evaluate("[...document.querySelectorAll('.card h3')].find(h=>h.textContent.startsWith('Your changes')).scrollIntoView({block:'start'});document.querySelector('.ovb').scrollTop-=60")
    await shot("10-your-changes-card")
    n0=len(await edits())
    k = [x for x in await edits() if x.get("src",{}).get("type")=="work"][0]["key"]
    await pg.evaluate("k=>document.querySelector(`[data-ereset=\"${k}\"]`).click()", k); await pg.wait_for_timeout(400)
    ok(len(await edits())==n0-1, "Reset in Your changes removes that edit")
    # reset from the event sheet
    w = await pg.evaluate("""(()=>{const i=[...document.querySelectorAll('.wg [data-wkb].ed')].find(i=>i.style.background.includes('--workout'));i.scrollIntoView({block:'center'});return i.dataset.wkb})()""")
    await pg.tap(f'.wg [data-wkb="{w}"]'); await pg.wait_for_timeout(300)
    ok(await pg.is_visible('#es_rs'), "edited event sheet has Reset to calendar")
    await shot("11-sheet-reset-to-calendar")
    await pg.tap('#es_rs'); await pg.wait_for_timeout(400)
    ok(not any(x.get("src",{}).get("type")=="workout" for x in await edits()), "Reset to calendar from the sheet")
    # ---- 7. persistence across reload + Today view gone everywhere ----
    n0=len(await edits()); await pg.goto(BASE+"?qa=1&open=schedule&view=today", wait_until="networkidle"); await pg.wait_for_timeout(600)
    ok(await pg.evaluate("document.querySelector('.ovh b').textContent")=="Week", "?open=schedule&view=today lands on Week")
    ok(await pg.evaluate("document.querySelectorAll('.wg [data-wkb].ed').length")>0 and len(await edits())==n0, "edits survive a reload")
    txt = await pg.evaluate("document.body.innerText")
    import re
    ok(not re.search(r"\b(AM|PM)\b", txt), "no AM/PM anywhere (24 h)")
    ok(await pg.evaluate("[...document.querySelectorAll('.wg [data-wkb]')].filter(i=>i.style.background.includes('--sleep')&&i.offsetHeight>=36).every(i=>i.innerText.includes('Sleep'))"), "tall Sleep blocks still say Sleep")
    await pg.click('[data-close]'); await pg.wait_for_timeout(600)
    await pg.click('[data-pg="1"]'); await pg.wait_for_timeout(600); await shot("12-sections-page")
    await pg.click('.page[data-pi="1"] [data-open="schedule"]'); await pg.wait_for_timeout(700)
    ok(await pg.evaluate("document.querySelector('.ovh b').textContent")=="Week", "home Today widget opens Week")
    ov = await pg.evaluate("document.documentElement.scrollWidth<=390 && document.querySelector('.ovb').scrollWidth<=390"); ok(ov, "no horizontal overflow")
    ok(not errs, f"no JS/console errors: {errs}")
    print("RESULT", "ALL PASS" if not FAIL else f"{len(FAIL)} FAIL: {FAIL}")
    await ctx.close(); await b.close()
asyncio.run(main())
